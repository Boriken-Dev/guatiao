  ! ---- calling another side's tables -----------------------------------

  ! The slot as a procedure, or a refusal when the table lacks it.
  recursive logical function gk_lacks(r, i, error)
    type(guatiao_remote), intent(in) :: r
    integer, intent(in) :: i
    type(guatiao_error), allocatable, intent(inout) :: error
    gk_lacks = .not. r%has(i)
    if (gk_lacks) then
      if (r%is_closed()) then
        call guatiao_fail(error, GUATIAO_ERR_GONE, 'the remote is closed')
      else
        call guatiao_fail(error, GUATIAO_ERR_UNSUPPORTED, 'the table has no such slot')
      end if
    end if
  end function

  recursive subroutine greeter_remote_greet(self, name, answer, error)
    class(greeter_remote), intent(inout) :: self
    character(*), intent(in) :: name
    type(guatiao_value), intent(inout) :: answer
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(greeter_greet_c), pointer :: gk_f
    type(gt_provider_error), target :: gk_err
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    character(:), allocatable, target :: gk_t1
    type(guatiao_value) :: gk_got
    type(c_ptr) :: gk_out
    if (gk_lacks(self%r, 1, error)) return
    call c_f_procpointer(self%r%slot(1), gk_f)
    gk_t1 = name
    call guatiao_map_out(gk_got, gk_out, self%r%alloc)
    gk_st = gk_f(self%r%ctx, guatiao_string_in(gk_t1), gk_out, c_loc(gk_err))
    call guatiao_call_error(gk_st, gk_err, error)
    if (gk_st /= GUATIAO_OK) return
    call guatiao_settle_home(gk_got, gk_ist)
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'the answer of greet could not be moved into the allocator of this side')
      return
    end if
    answer = gk_got
  end subroutine

  recursive subroutine greeter_remote_shout(self, name, answer, error)
    class(greeter_remote), intent(inout) :: self
    character(*), intent(in) :: name
    character(:), allocatable, intent(out) :: answer
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(greeter_shout_c), pointer :: gk_f
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    character(:), allocatable, target :: gk_t1
    type(gt_owned), target :: gk_out
    type(gt_value), target :: gk_node
    type(guatiao_value) :: gk_said
    answer = ''
    if (gk_lacks(self%r, 2, error)) return
    call c_f_procpointer(self%r%slot(2), gk_f)
    gk_t1 = name
    gk_st = gk_f(self%r%ctx, guatiao_string_in(gk_t1), c_loc(gk_out))
    if (gk_st /= GUATIAO_OK) call guatiao_fail(error, int(gk_st), 'shout failed')
    if (gk_st /= GUATIAO_OK) return
    gk_node%tag = GUATIAO_TAG_STRING
    gk_node%payload = gk_out
    gk_said = guatiao_value_from_raw(c_loc(gk_node))
    answer = gk_said%string_or('')
  end subroutine

  recursive subroutine greeter_remote_start(self, listener_in, answer, error)
    class(greeter_remote), intent(inout) :: self
    class(listener), allocatable, intent(inout) :: listener_in
    class(conversation), allocatable, intent(out) :: answer
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(greeter_start_c), pointer :: gk_f
    type(gt_provider_error), target :: gk_err
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    type(gt_object), target :: gk_o1
    class(guatiao_impl), allocatable :: gk_m1
    logical :: gk_r1
    type(gt_object), target :: gk_got
    if (gk_lacks(self%r, 3, error)) return
    call c_f_procpointer(self%r%slot(3), gk_f)
    if (.not. allocated(listener_in)) then
      call guatiao_fail(error, GUATIAO_ERR_NULL, 'no listener to hand over as listener_in')
      return
    end if
    gk_ist = GUATIAO_OK
    gk_r1 = .false.
    select type (listener_in)
    type is (listener_remote)
      call listener_in%r%give(gk_o1, gk_ist)
      gk_r1 = .true.
    end select
    if (gk_r1) then
      deallocate(listener_in)
    else
      call move_alloc(listener_in, gk_m1)
      call guatiao_serve_object(gk_m1, listener_kind(), gk_o1)
    end if
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'a listener this side does not own cannot be handed over')
      return
    end if
#if defined(__flang__) && (defined(__aarch64__) || defined(_WIN32))
    gk_st = gk_f(self%r%ctx, c_loc(gk_o1), c_loc(gk_got), c_loc(gk_err))
#else
    gk_st = gk_f(self%r%ctx, gk_o1, c_loc(gk_got), c_loc(gk_err))
#endif
    call guatiao_call_error(gk_st, gk_err, error)
    if (gk_st /= GUATIAO_OK) return
    allocate(conversation_remote :: answer)
    select type (answer)
    type is (conversation_remote)
      call guatiao_take_object(gk_got, conversation_kind(), answer%r, gk_ist)
    end select
    if (gk_ist /= GUATIAO_OK) call guatiao_fail(error, gk_ist, 'the answer is not a conversation')
  end subroutine

  recursive subroutine greeter_remote_greet_into(self, name, listener_in, error)
    class(greeter_remote), intent(inout) :: self
    character(*), intent(in) :: name
    class(listener), intent(inout), target :: listener_in
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(greeter_greet_into_c), pointer :: gk_f
    type(gt_provider_error), target :: gk_err
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    character(:), allocatable, target :: gk_t1
    type(gt_object), target :: gk_o2
    logical :: gk_w2
    if (gk_lacks(self%r, 4, error)) return
    call c_f_procpointer(self%r%slot(4), gk_f)
    gk_t1 = name
    gk_w2 = .false.
    select type (listener_in)
    type is (listener_remote)
      gk_o2%table = listener_in%r%table
      gk_o2%size = listener_in%r%size
      gk_o2%ctx = listener_in%r%ctx
    class default
      call guatiao_lend_impl(listener_in, listener_kind(), gk_o2)
      gk_w2 = .true.
    end select
    gk_st = gk_f(self%r%ctx, guatiao_string_in(gk_t1), c_loc(gk_o2), c_loc(gk_err))
    if (gk_w2) call guatiao_destroy_served(gk_o2%ctx, close=.false.)
    call guatiao_call_error(gk_st, gk_err, error)
  end subroutine

  recursive subroutine greeter_remote_greet_from(self, config, answer, error)
    class(greeter_remote), intent(inout) :: self
    type(guatiao_value), intent(inout) :: config
    type(guatiao_value), intent(inout) :: answer
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(greeter_greet_from_c), pointer :: gk_f
    type(gt_provider_error), target :: gk_err
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    type(gt_value), target :: gk_n1
    type(guatiao_value) :: gk_got
    type(c_ptr) :: gk_out
    if (gk_lacks(self%r, 5, error)) return
    call c_f_procpointer(self%r%slot(5), gk_f)
    if (config%tag() /= GUATIAO_TAG_MAP) then
      call guatiao_fail(error, merge(GUATIAO_ERR_NULL, GUATIAO_ERR_WRONG_KIND, config%is_absent()), 'greet_from takes a &
        &map as config')
      return
    end if
    call guatiao_hand_over(config, GUATIAO_TAG_MAP, gk_n1, gk_ist)
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'greet_from takes a map as config')
      return
    end if
    call guatiao_map_out(gk_got, gk_out, self%r%alloc)
    gk_st = gk_f(self%r%ctx, c_loc(gk_n1%payload), gk_out, c_loc(gk_err))
    call guatiao_call_error(gk_st, gk_err, error)
    if (gk_st /= GUATIAO_OK) return
    call guatiao_settle_home(gk_got, gk_ist)
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'the answer of greet_from could not be moved into the allocator of this side')
      return
    end if
    answer = gk_got
  end subroutine

  recursive subroutine greeter_remote_check(self, config, answer, error)
    class(greeter_remote), intent(inout) :: self
    type(guatiao_value), intent(inout) :: config
    logical, intent(out) :: answer
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(greeter_check_c), pointer :: gk_f
    type(gt_provider_error), target :: gk_err
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    type(c_ptr) :: gk_l1, gk_h1
    integer :: gk_s1
    integer(c_int8_t), target :: gk_out
    answer = .false.
    if (gk_lacks(self%r, 6, error)) return
    call c_f_procpointer(self%r%slot(6), gk_f)
    call guatiao_lend_tree(config, GUATIAO_TAG_MAP, gk_l1, gk_ist, gk_h1)
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'check takes a writable map as config')
      return
    end if
    gk_out = GUATIAO_C_FALSE
    gk_st = gk_f(self%r%ctx, gk_l1, c_loc(gk_out), c_loc(gk_err))
    call guatiao_settle_lent(config, GUATIAO_TAG_MAP, gk_h1, gk_s1)
    call guatiao_call_error(gk_st, gk_err, error)
    if (gk_st /= GUATIAO_OK) return
    if (gk_s1 /= GUATIAO_OK) then
      call guatiao_fail(error, gk_s1, guatiao_lent_refusal(gk_s1, "check", "config"))
      return
    end if
    answer = gk_out /= GUATIAO_C_FALSE
  end subroutine

