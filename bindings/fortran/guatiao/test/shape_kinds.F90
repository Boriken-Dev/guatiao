  recursive subroutine shapes_remote_keep(self, n, error)
    class(shapes_remote), intent(inout) :: self
    class(note), allocatable, intent(inout) :: n
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(shapes_keep_c), pointer :: gk_f
    type(gt_provider_error), target :: gk_err
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    type(gt_object), target :: gk_o1
    class(guatiao_impl), allocatable :: gk_m1
    logical :: gk_r1
    if (gk_lacks(self%r, 9, error)) return
    call c_f_procpointer(self%r%slot(9), gk_f)
    if (.not. allocated(n)) then
      call guatiao_fail(error, GUATIAO_ERR_NULL, 'no note to hand over as n')
      return
    end if
    gk_ist = GUATIAO_OK
    gk_r1 = .false.
    select type (n)
    type is (note_remote)
      call n%r%give(gk_o1, gk_ist)
      gk_r1 = .true.
    end select
    if (gk_r1) then
      deallocate(n)
    else
      call move_alloc(n, gk_m1)
      call guatiao_serve_object(gk_m1, note_kind(), gk_o1)
    end if
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'a note this side does not own cannot be handed over')
      return
    end if
#if defined(__flang__) && (defined(__aarch64__) || defined(_WIN32))
    gk_st = gk_f(self%r%ctx, c_loc(gk_o1), c_loc(gk_err))
#else
    gk_st = gk_f(self%r%ctx, gk_o1, c_loc(gk_err))
#endif
    call guatiao_call_error(gk_st, gk_err, error)
  end subroutine

  recursive subroutine shapes_remote_poke(self, n, answer, error)
    class(shapes_remote), intent(inout) :: self
    class(note), intent(inout), target :: n
    integer(int64), intent(out) :: answer
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(shapes_poke_c), pointer :: gk_f
    type(gt_provider_error), target :: gk_err
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    type(gt_object), target :: gk_o1
    logical :: gk_w1
    integer(c_int64_t), target :: gk_out
    answer = 0
    if (gk_lacks(self%r, 10, error)) return
    call c_f_procpointer(self%r%slot(10), gk_f)
    gk_w1 = .false.
    select type (n)
    type is (note_remote)
      gk_o1%table = n%r%table
      gk_o1%size = n%r%size
      gk_o1%ctx = n%r%ctx
    class default
      call guatiao_lend_impl(n, note_kind(), gk_o1)
      gk_w1 = .true.
    end select
    gk_out = 0
    gk_st = gk_f(self%r%ctx, c_loc(gk_o1), c_loc(gk_out), c_loc(gk_err))
    if (gk_w1) call guatiao_destroy_served(gk_o1%ctx, close=.false.)
    call guatiao_call_error(gk_st, gk_err, error)
    if (gk_st /= GUATIAO_OK) return
    answer = gk_out
  end subroutine

