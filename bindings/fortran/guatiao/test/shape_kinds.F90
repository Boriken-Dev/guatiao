  !> Whether the table has the slot named `slot`.
  recursive logical function shapes_remote_has(self, slot)
    class(shapes_remote), intent(in) :: self
    character(*), intent(in) :: slot
    integer :: i
    select case (slot)
    case ('scalars'); i = 1
    case ('flag'); i = 2
    case ('split'); i = 3
    case ('sum'); i = 4
    case ('borrow'); i = 5
    case ('lend'); i = 6
    case ('take'); i = 7
    case ('number'); i = 8
    case ('keep'); i = 9
    case ('poke'); i = 10
    case ('make'); i = 11
    case ('echo'); i = 12
    case ('quiet'); i = 13
    case default; i = 0
    end select
    shapes_remote_has = .false.
    if (i > 0) shapes_remote_has = self%r%has(i)
  end function

