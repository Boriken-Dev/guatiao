  end subroutine

  recursive subroutine shapes_remote_borrow(self, m, v, n, answer, error)
    class(shapes_remote), intent(inout) :: self
    type(guatiao_value), intent(in) :: m
    type(guatiao_value), intent(in) :: v
    type(guatiao_value), intent(in) :: n
    type(guatiao_value), intent(inout) :: answer
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(shapes_borrow_c), pointer :: gk_f
    type(gt_provider_error), target :: gk_err
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    type(c_ptr) :: gk_p1
    type(c_ptr) :: gk_p2
    type(c_ptr) :: gk_p3
    type(guatiao_value) :: gk_got
    type(c_ptr) :: gk_out
    if (gk_lacks(self%r, 5, error)) return
    call c_f_procpointer(self%r%slot(5), gk_f)
    call guatiao_borrow_tree(m, GUATIAO_TAG_MAP, gk_p1, gk_ist)
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'borrow borrows a map as m')
      return
    end if
    call guatiao_borrow_tree(v, GUATIAO_TAG_ABSENT, gk_p2, gk_ist)
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'borrow borrows a value as v')
      return
    end if
    call guatiao_borrow_tree(n, GUATIAO_TAG_ABSENT, gk_p3, gk_ist)
    if (gk_ist == GUATIAO_ERR_NULL) gk_ist = GUATIAO_OK
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'borrow borrows a value as n')
      return
    end if
    call guatiao_map_out(gk_got, gk_out, self%r%alloc)
    gk_st = gk_f(self%r%ctx, gk_p1, gk_p2, gk_p3, gk_out, c_loc(gk_err))
    call guatiao_call_error(gk_st, gk_err, error)
    if (gk_st /= GUATIAO_OK) return
    call guatiao_settle_home(gk_got, gk_ist)
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'the answer of borrow could not be moved into the allocator of this side')
      return
    end if
    answer = gk_got
  end subroutine

  recursive subroutine shapes_remote_lend(self, m, l, answer, error)
    class(shapes_remote), intent(inout) :: self
    type(guatiao_value), intent(inout) :: m
    type(guatiao_value), intent(inout) :: l
    logical, intent(out) :: answer
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(shapes_lend_c), pointer :: gk_f
    type(gt_provider_error), target :: gk_err
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    type(c_ptr) :: gk_l1, gk_h1
    integer :: gk_s1
    type(c_ptr) :: gk_l2, gk_h2
    integer :: gk_s2
    integer(c_int8_t), target :: gk_out
    answer = .false.
    if (gk_lacks(self%r, 6, error)) return
    call c_f_procpointer(self%r%slot(6), gk_f)
    call guatiao_lend_tree(m, GUATIAO_TAG_MAP, gk_l1, gk_ist, gk_h1)
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'lend takes a writable map as m')
      return
    end if
    call guatiao_lend_tree(l, GUATIAO_TAG_LIST, gk_l2, gk_ist, gk_h2)
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'lend takes a writable list as l')
      return
    end if
    gk_out = GUATIAO_C_FALSE
    gk_st = gk_f(self%r%ctx, gk_l1, gk_l2, c_loc(gk_out), c_loc(gk_err))
    call guatiao_settle_lent(m, GUATIAO_TAG_MAP, gk_h1, gk_s1)
    call guatiao_settle_lent(l, GUATIAO_TAG_LIST, gk_h2, gk_s2)
    call guatiao_call_error(gk_st, gk_err, error)
    if (gk_st /= GUATIAO_OK) return
    if (gk_s1 /= GUATIAO_OK) then
      call guatiao_fail(error, gk_s1, guatiao_lent_refusal(gk_s1, "lend", "m"))
      return
    end if
    if (gk_s2 /= GUATIAO_OK) then
      call guatiao_fail(error, gk_s2, guatiao_lent_refusal(gk_s2, "lend", "l"))
      return
    end if
    answer = gk_out /= GUATIAO_C_FALSE
  end subroutine

  recursive subroutine shapes_remote_take(self, m, l, answer, error)
    class(shapes_remote), intent(inout) :: self
    type(guatiao_value), intent(inout) :: m
    type(guatiao_value), intent(inout) :: l
    type(guatiao_value), intent(inout) :: answer
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(shapes_take_c), pointer :: gk_f
    type(gt_provider_error), target :: gk_err
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    type(gt_value), target :: gk_n1
    type(gt_value), target :: gk_n2
    type(guatiao_value) :: gk_got
    type(c_ptr) :: gk_out
    if (gk_lacks(self%r, 7, error)) return
    call c_f_procpointer(self%r%slot(7), gk_f)
    if (m%tag() /= GUATIAO_TAG_MAP) then
      call guatiao_fail(error, merge(GUATIAO_ERR_NULL, GUATIAO_ERR_WRONG_KIND, m%is_absent()), 'take takes a map as m')
      return
    end if
    if (l%tag() /= GUATIAO_TAG_LIST) then
      call guatiao_fail(error, merge(GUATIAO_ERR_NULL, GUATIAO_ERR_WRONG_KIND, l%is_absent()), 'take takes a list as l')
      return
    end if
    call guatiao_hand_over(m, GUATIAO_TAG_MAP, gk_n1, gk_ist)
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'take takes a map as m')
      return
    end if
    call guatiao_hand_over(l, GUATIAO_TAG_LIST, gk_n2, gk_ist)
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'take takes a list as l')
      return
    end if
    call guatiao_list_out(gk_got, gk_out, self%r%alloc)
    gk_st = gk_f(self%r%ctx, c_loc(gk_n1%payload), c_loc(gk_n2%payload), gk_out, c_loc(gk_err))
    call guatiao_call_error(gk_st, gk_err, error)
    if (gk_st /= GUATIAO_OK) return
    call guatiao_settle_home(gk_got, gk_ist)
    if (gk_ist /= GUATIAO_OK) then
      call guatiao_fail(error, gk_ist, 'the answer of take could not be moved into the allocator of this side')
      return
    end if
    answer = gk_got
  end subroutine

