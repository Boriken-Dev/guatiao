    integer(int32), intent(in) :: a
    integer(int32), intent(in) :: b
    integer(int32), intent(in) :: c
    character(*), intent(in) :: s
    character(:), allocatable, intent(out) :: answer
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(shapes_split_c), pointer :: gk_f
    type(gt_provider_error), target :: gk_err
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    character(:), allocatable, target :: gk_t4
    type(gt_str) :: gk_v4
    type(gt_owned), target :: gk_out
    type(gt_value), target :: gk_node
    type(guatiao_value) :: gk_said
    answer = ''
    if (gk_lacks(self%r, 3, error)) return
    call c_f_procpointer(self%r%slot(3), gk_f)
    gk_t4 = s
    gk_v4 = guatiao_string_in(gk_t4)
#if defined(__flang__) && defined(__x86_64__) && !defined(_WIN32)
    gk_st = gk_f(self%r%ctx, a, b, c, gk_v4%ptr, gk_v4%len, c_loc(gk_out), c_loc(gk_err))
#else
    gk_st = gk_f(self%r%ctx, a, b, c, guatiao_string_in(gk_t4), c_loc(gk_out), c_loc(gk_err))
#endif
    call guatiao_call_error(gk_st, gk_err, error)
    if (gk_st /= GUATIAO_OK) return
    gk_node%tag = GUATIAO_TAG_STRING
    gk_node%payload = gk_out
    gk_said = guatiao_value_from_raw(c_loc(gk_node))
    answer = gk_said%string_or('')
  end subroutine

  recursive subroutine shapes_remote_sum(self, data, answer, error)
    class(shapes_remote), intent(inout) :: self
    integer(int8), intent(in) :: data(:)
    integer(int32), intent(out) :: answer
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(shapes_sum_c), pointer :: gk_f
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    integer(int8), allocatable, target :: gk_b1(:)
    type(gt_bytes_mut) :: gk_v1
    integer(c_int32_t), target :: gk_out
    answer = 0
    if (gk_lacks(self%r, 4, error)) return
