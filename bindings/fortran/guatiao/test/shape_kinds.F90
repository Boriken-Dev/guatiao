    class(note_remote), intent(inout) :: self
    integer(int8), intent(inout) :: dst(:)
    integer(int64), intent(out) :: answer
    type(guatiao_error), allocatable, intent(out) :: error
    procedure(note_fill_c), pointer :: gk_f
    integer(c_int32_t) :: gk_st
    integer :: gk_ist
    integer(int8), allocatable, target :: gk_b1(:)
    type(gt_bytes_mut) :: gk_v1
    integer(c_int64_t), target :: gk_out
    answer = 0
    if (gk_lacks(self%r, 3, error)) return
    call c_f_procpointer(self%r%slot(3), gk_f)
    gk_b1 = dst
    gk_v1%len = size(gk_b1, kind=c_size_t)
    if (gk_v1%len > 0) gk_v1%ptr = c_loc(gk_b1)
    gk_out = 0
    gk_st = gk_f(self%r%ctx, gk_v1, c_loc(gk_out))
    dst = gk_b1
    if (gk_st /= GUATIAO_OK) call guatiao_fail(error, int(gk_st), 'fill failed')
    if (gk_st /= GUATIAO_OK) return
