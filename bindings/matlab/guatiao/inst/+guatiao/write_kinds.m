function files = write_kinds(document, folder, varargin)
% Writes a kind class per kind a description document holds (the
% <crate>.kinds.json a kind crate commits, or one written by another
% language) into a package folder, one <Kind>.m each:
%
%   guatiao.write_kinds('../include/greeter_kind.kinds.json', '+greeterkind')
%   guatiao.write_kinds(doc, '+greeterkind', 'Check', true)   % error when stale
%
% Each is a classdef inheriting guatiao.Kind, named in PascalCase
% (session_backend is SessionBackend), with its description as the
% <Class>Kind constant and a method per slot calling self.call, the
% description's docs as their help. An object kind a slot takes or
% answers is named by the package the folder is (+a/+b is a.b). 'Check',
% true writes nothing and raises guatiao:Stale when a file is not what it
% would write, or one it wrote names a kind the document no longer holds
% (writing removes those). A document no class can be written from raises
% guatiao:BadValue naming the slot, and nothing is written. Names are
% checked against MATLAB's keywords and Octave's alike, so either
% interpreter writes the same files. Answers the files' paths.
  o = guatiao.internal.options(varargin, struct('Check', false));
  if isa(document, 'string')
    document = char(document);
  end
  if isa(folder, 'string')
    folder = char(folder);
  end
  if ~ischar(document) || ~exist(document, 'file')
    error('guatiao:NotFound', 'no kinds document at %s', document);
  end
  [~, base, ext] = fileparts(document);
  source = [base ext];
  doc = jsondecode(read_utf8(document));
  if ~isstruct(doc) || ~isfield(doc, 'kinds')
    error('guatiao:BadValue', '%s: a kinds document is {"kinds": [...]}', source);
  end
  pkg = package_of(folder);
  kinds = items(doc.kinds);
  classes = containers.Map('KeyType', 'char', 'ValueType', 'char');
  objects = containers.Map('KeyType', 'char', 'ValueType', 'logical');
  for i = 1:numel(kinds)
    cls = class_name(kinds{i}.name);
    if any(strcmp(values(classes), cls))
      error('guatiao:BadValue', '%s: two kinds are %s in M', source, cls);
    end
    classes(kinds{i}.name) = cls;
    objects(kinds{i}.name) = logical(field(kinds{i}, 'object', false));
  end
  % Every class is made before any is written: a refusal writes nothing.
  files = cell(1, numel(kinds));
  texts = cell(1, numel(kinds));
  for i = 1:numel(kinds)
    texts{i} = kind_file(kinds{i}, classes, objects, pkg, source);
    files{i} = fullfile(folder, [classes(kinds{i}.name) '.m']);
  end
  % What this function wrote before for a kind the document no longer holds.
  orphans = {};
  if exist(folder, 'dir')
    listed = dir(fullfile(folder, '*.m'));
    for i = 1:numel(listed)
      path = fullfile(folder, listed(i).name);
      if ~any(strcmp(files, path)) && strncmp(read_utf8(path), generated(), numel(generated()))
        orphans{end + 1} = path; %#ok<AGROW>
      end
    end
  end
  if o.Check
    stale = orphans;
    for i = 1:numel(files)
      if ~exist(files{i}, 'file') || ~strcmp(read_utf8(files{i}), texts{i})
        stale{end + 1} = files{i}; %#ok<AGROW>
      end
    end
    if ~isempty(stale)
      error('guatiao:Stale', '%s is not what guatiao.write_kinds writes from %s: write them again', ...
            strjoin(stale, ', '), source);
    end
    return
  end
  if ~exist(folder, 'dir')
    mkdir(folder);
  end
  for i = 1:numel(files)
    write_utf8(files{i}, texts{i});
  end
  for i = 1:numel(orphans)
    delete(orphans{i});
  end
end

function g = generated()
  g = '% GENERATED by guatiao.write_kinds from ';
end

function tf = is_name(n)
% An M identifier that is no keyword in MATLAB or in Octave.
  keywords = {'break', 'case', 'catch', 'classdef', 'continue', 'do', 'else', 'elseif', 'end', ...
              'end_try_catch', 'end_unwind_protect', 'endclassdef', 'endenumeration', 'endevents', ...
              'endfor', 'endfunction', 'endif', 'endmethods', 'endparfor', 'endproperties', 'endspmd', ...
              'endswitch', 'endwhile', 'enumeration', 'events', 'for', 'function', 'global', 'if', ...
              'methods', 'otherwise', 'parfor', 'persistent', 'properties', 'return', 'spmd', 'switch', ...
              'try', 'unwind_protect', 'unwind_protect_cleanup', 'until', 'while', ...
              'varargin', 'varargout', 'nargin', 'nargout'};
  tf = ischar(n) && ~isempty(regexp(n, '^[A-Za-z][A-Za-z0-9_]{0,62}$', 'once')) && ~any(strcmp(n, keywords));
end

function q = quoted(s)
% Text as an M character literal.
  apostrophe = char(39);
  q = [apostrophe strrep(s, apostrophe, [apostrophe apostrophe]) apostrophe];
end

function pkg = package_of(folder)
  parts = regexp(strrep(folder, '\', '/'), '[^/]+', 'match');
  i = numel(parts);
  while i >= 1 && strncmp(parts{i}, '+', 1)
    i = i - 1;
  end
  parts = parts(i + 1:end);
  if isempty(parts)
    error('guatiao:BadValue', '%s is no package folder: its name starts with +', folder);
  end
  pkg = strjoin(cellfun(@(p) p(2:end), parts, 'UniformOutput', false), '.');
end

function c = items(x)
% A JSON array as jsondecode answers it (a struct array, a cell, or []),
% as a cell.
  if iscell(x)
    c = reshape(x, 1, []);
  elseif isstruct(x)
    c = reshape(num2cell(x), 1, []);
  else
    c = {};
  end
end

function v = field(s, name, default)
  if isfield(s, name) && ~isempty(s.(name))
    v = s.(name);
  else
    v = default;
  end
end

function cls = class_name(kind)
  parts = regexp(kind, '[A-Za-z0-9]+', 'match');
  cls = strjoin(cellfun(@(p) [upper(p(1)) p(2:end)], parts, 'UniformOutput', false), '');
  if ~is_name(cls)
    error('guatiao:BadValue', 'the kind "%s" names no M class', kind);
  end
end

function n = arg_name(name, i)
  n = name;
  if ~is_name(n)
    n = sprintf('arg%d', i);
  end
  if any(strcmp(n, {'self', 'out'}))
    n = [n '_'];
  end
end

function shape = shape_of(t, classes, objects, pkg, where)
  scalars = struct('bool', 'bool', 'i8', 'int8', 'i16', 'int16', 'i32', 'int32', 'i64', 'int64', ...
                   'u8', 'uint8', 'u16', 'uint16', 'u32', 'uint32', 'u64', 'uint64', ...
                   'isize', 'intptr', 'usize', 'size', 'f32', 'float', 'f64', 'double');
  type = t.type;
  pass = field(t, 'pass', 'borrowed');
  if isfield(scalars, type)
    shape = quoted(scalars.(type));
    return
  end
  switch type
    case 'str'
      shape = quoted('string');
    case 'bytes'
      shape = quoted('bytes');
    case 'bytes_mut'
      shape = ['guatiao.lent(' quoted('bytes') ')'];
    case {'value', 'map', 'list'}
      switch pass
        case 'borrowed'
          if strcmp(type, 'list')
            error('guatiao:BadValue', '%s: a list is not borrowed', where);
          end
          shape = quoted(type);
        case {'lent', 'taken'}
          shape = ['guatiao.' pass '(' quoted(type) ')'];
        otherwise
          error('guatiao:BadValue', '%s: a %s is passed borrowed, taken or lent, not %s', where, type, pass);
      end
    case 'object'
      cls = object_class(t, classes, objects, pkg, where);
      if ~any(strcmp(pass, {'lent', 'taken'}))
        error('guatiao:BadValue', '%s: an object is passed taken or lent, not %s', where, pass);
      end
      shape = ['guatiao.' pass '(' quoted(cls) ')'];
    otherwise
      error('guatiao:BadValue', '%s: %s is not a type an argument can have', where, type);
  end
end

function shape = answer_of(t, classes, objects, pkg, where)
  if isempty(t)
    shape = '';
    return
  end
  switch t.type
    case 'text'
      shape = quoted('string');
    case {'value', 'map', 'list'}
      shape = quoted(t.type);
    case 'object'
      shape = quoted(object_class(t, classes, objects, pkg, where));
    case {'str', 'bytes', 'bytes_mut'}
      error('guatiao:BadValue', '%s: an answer cannot be %s', where, t.type);
    otherwise
      shape = shape_of(t, classes, objects, pkg, where);
  end
end

function cls = object_class(t, classes, objects, pkg, where)
  kind = field(t, 'kind', '');
  if ~ischar(kind) || ~isKey(classes, kind)
    error('guatiao:BadValue', '%s: the object kind %s is not in this document', where, kind);
  end
  if ~objects(kind)
    error('guatiao:BadValue', '%s: %s is a kind but no object kind', where, kind);
  end
  cls = [pkg '.' classes(kind)];
end

function lines = help(doc, indent)
% A doc as M help: each line behind '% '.
  lines = {};
  if isempty(doc)
    return
  end
  doc = strrep(strrep(doc, sprintf('\r\n'), sprintf('\n')), sprintf('\r'), sprintf('\n'));
  for l = regexp(doc, '\n', 'split')
    if isempty(l{1})
      lines{end + 1} = [indent '%']; %#ok<AGROW>
    else
      lines{end + 1} = [indent '% ' l{1}]; %#ok<AGROW>
    end
  end
end

function text = kind_file(k, classes, objects, pkg, source)
  cls = classes(k.name);
  object = objects(k.name);
  slots = items(field(k, 'slots', []));
  % guatiao.Kind's members, and handle's.
  reserved = {'has_slot', 'is_bound', 'close', 'call', 'attach', 'detach', 'check_bound', 'describe', ...
              'delete', 'Ref', 'Holder', 'RemoteId', 'addlistener', 'listener', 'notify', 'findobj', ...
              'findprop', 'isvalid', 'eq', 'ne', 'lt', 'le', 'gt', 'ge'};
  lines = {[generated() source '. DO NOT EDIT.'], '', sprintf('classdef %s < guatiao.Kind', cls)};
  kind_doc = field(k, 'doc', '');
  lines = [lines, help(kind_doc, '')];
  if ~isempty(kind_doc)
    lines{end + 1} = '%';
  end
  what = 'a provider of it implements its methods';
  if object
    what = 'an object kind: its destroy slot is close()';
  end
  lines{end + 1} = sprintf('%% The %s kind (floor hash %d): %s.', k.name, k.floor_hash, what);
  lines = [lines, {'', '  properties (Constant, Hidden)'}];
  head = sprintf('    %sKind = guatiao.Kind.describe(%s, %d', cls, quoted(k.name), k.floor_hash);
  if object
    head = [head ', ' quoted('Object') ', true'];
  end
  entries = {};
  methods = {};
  slot_names = {};
  for i = 1:numel(slots)
    s = slots{i};
    where = sprintf('%s.%s', k.name, s.name);
    if ~is_name(s.name) || any(strcmp(s.name, reserved))
      error('guatiao:BadValue', '%s: %s names no method a kind class may have', where, s.name);
    end
    if any(strcmp(slot_names, s.name))
      error('guatiao:BadValue', '%s: two slots are %s', where, s.name);
    end
    slot_names{end + 1} = s.name; %#ok<AGROW>
    args = items(field(s, 'args', []));
    names = cell(1, numel(args));
    pairs = cell(1, numel(args));
    hints = {};
    for j = 1:numel(args)
      names{j} = arg_name(field(args{j}, 'name', ''), j - 1);
      if any(strcmp(names(1:j - 1), names{j}))
        error('guatiao:BadValue', '%s: two arguments are %s in M', where, names{j});
      end
      shape = shape_of(args{j}, classes, objects, pkg, sprintf('%s(%s)', where, names{j}));
      pairs{j} = [quoted(names{j}) ', ' shape];
      if strcmp(args{j}.type, 'bytes_mut')
        if ~object
          error('guatiao:BadValue', '%s(%s): bytes written in place cross on an object kind only', where, names{j});
        end
        hints{end + 1} = sprintf('    %% `%s` is a guatiao.Buffer, written in place.', names{j}); %#ok<AGROW>
      elseif strcmp(args{j}.type, 'i64')
        hints{end + 1} = sprintf('    %% `%s` is an int64: a double is exact only to 2^53.', names{j}); %#ok<AGROW>
      elseif strcmp(args{j}.type, 'u64')
        hints{end + 1} = sprintf('    %% `%s` is a uint64: a double is exact only to 2^53.', names{j}); %#ok<AGROW>
      end
    end
    answer = answer_of(field(s, 'answer', []), classes, objects, pkg, where);
    entry = sprintf('      guatiao.slot(%s, {%s}', quoted(s.name), strjoin(pairs, ', '));
    if ~isempty(answer)
      entry = [entry ', ' quoted('Returns') ', ' answer];
    end
    if s.required
      entry = [entry ', ' quoted('Required') ', true'];
    end
    if s.fallible
      entry = [entry ', ' quoted('Fallible') ', true'];
    end
    entries{end + 1} = [entry ')']; %#ok<AGROW>
    call_args = strjoin([{quoted(s.name)}, names], ', ');
    params = strjoin([{'self'}, names], ', ');
    if isempty(answer)
      m = {sprintf('    function %s(%s)', s.name, params)};
      body = sprintf('      self.call(%s);', call_args);
    else
      m = {sprintf('    function out = %s(%s)', s.name, params)};
      body = sprintf('      out = self.call(%s);', call_args);
    end
    doc_lines = help(field(s, 'doc', ''), '    ');
    if ~isempty(doc_lines) && ~isempty(hints)
      doc_lines{end + 1} = '    %'; %#ok<AGROW>
    end
    m = [m, doc_lines, hints, {body, '    end'}];
    methods{end + 1} = m; %#ok<AGROW>
  end
  if isempty(entries)
    lines{end + 1} = [head ')'];
  else
    lines{end + 1} = [head ', ...'];
    for i = 1:numel(entries)
      if i < numel(entries)
        lines{end + 1} = [entries{i} ', ...']; %#ok<AGROW>
      else
        lines{end + 1} = [entries{i} ')']; %#ok<AGROW>
      end
    end
  end
  lines = [lines, {'  end'}];
  if ~isempty(methods)
    lines = [lines, {'', '  methods'}];
    for i = 1:numel(methods)
      if i > 1
        lines{end + 1} = ''; %#ok<AGROW>
      end
      lines = [lines, methods{i}]; %#ok<AGROW>
    end
    lines = [lines, {'  end'}];
  end
  lines = [lines, {'end'}];
  text = [strjoin(lines, char(10)) char(10)];
end

function t = read_utf8(path)
  fid = fopen(path, 'r');
  if fid < 0
    error('guatiao:NotFound', 'cannot open %s', path);
  end
  bytes = fread(fid, Inf, '*uint8')';
  fclose(fid);
  t = native2unicode(bytes, 'UTF-8');
end

function write_utf8(path, text)
  fid = fopen(path, 'w');
  if fid < 0
    error('guatiao:Internal', 'cannot write %s', path);
  end
  fwrite(fid, unicode2native(text, 'UTF-8'));
  fclose(fid);
end
